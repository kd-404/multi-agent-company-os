// ---------- brand imagery (hero / farm / banners generated by the image model) ----------
// Shows the generated image when it exists; otherwise the CSS fallback gradient stays.
function applyBrandImage(el, key) {
  if (!el) return;
  const img = new Image();
  img.onload = () => {
    el.style.backgroundImage = `url("${img.src}")`;
    el.classList.add("has-photo");
  };
  img.src = `/api/public/brand/${key}`;
}

// ---------- product card ----------
function productCard(p) {
  const off = p.mrp_inr > p.price_inr ? Math.round(100 * (p.mrp_inr - p.price_inr) / p.mrp_inr) : 0;
  const stock = p.stock || {};
  const chip = stock.state === "out" ? `<span class="chip chip-out">Sold out</span>`
    : stock.state === "low" ? `<span class="chip chip-low">${escapeHtml(stock.label)}</span>` : "";
  const match = typeof p.similarity === "number" ? `<span class="chip chip-match">${p.similarity}% match</span>` : "";
  return `
  <a class="pcard" href="/shop/design/${p.id}" aria-label="${escapeHtml(p.title)}">
    <div class="pcard-media">
      <img class="img-a" src="${p.mockups.front}" alt="${escapeHtml(p.title)}" loading="lazy" />
      <img class="img-b" src="${p.mockups.model}" alt="" loading="lazy" onerror="this.remove()" />
      <div class="pcard-chips">${match}${chip}</div>
    </div>
    <div class="pcard-body">
      <p class="pcard-kind">${escapeHtml(p.garment_label || "")}${p.color_label ? " · " + escapeHtml(p.color_label) : ""}</p>
      <h3 class="pcard-title">${escapeHtml(p.title)}</h3>
      <p class="pcard-price"><strong>${inr(p.price_inr)}</strong> <s>${inr(p.mrp_inr)}</s> ${off ? `<span class="off">${off}% off</span>` : ""}</p>
    </div>
  </a>`;
}

// ---------- account ----------
let currentUser = null;
let afterLogin = null;

async function refreshAccountState() {
  const label = $("#account-line-1");
  try {
    const res = await fetch("/api/me");
    if (res.ok) {
      currentUser = await res.json();
      if (label) label.textContent = currentUser.email.split("@")[0];
      $("#account-email").textContent = currentUser.email;
      $("#account-signed-in").classList.remove("hidden");
      $("#account-signed-out").classList.add("hidden");
      $("#account-staff-link").classList.toggle("hidden", currentUser.role === "user");
      return currentUser;
    }
  } catch {}
  currentUser = null;
  if (label) label.textContent = "Sign in";
  $("#account-signed-in")?.classList.add("hidden");
  $("#account-signed-out")?.classList.remove("hidden");
  return null;
}

function openAccountModal() { $("#account-backdrop").hidden = false; }
function closeAccountModal() { $("#account-backdrop").hidden = true; }

// Resolves true once the shopper is signed in (opens the modal if not).
function requireLogin() {
  if (currentUser) return Promise.resolve(true);
  return new Promise((resolve) => {
    afterLogin = resolve;
    openAccountModal();
  });
}

function switchAccountTab(which) {
  $("#account-tab-login").classList.toggle("active", which === "login");
  $("#account-tab-register").classList.toggle("active", which === "register");
  $("#account-login-form").classList.toggle("hidden", which !== "login");
  $("#account-register-form").classList.toggle("hidden", which !== "register");
}

async function postForm(url, form) {
  const res = await fetch(url, { method: "POST", body: form });
  let data = {};
  try { data = await res.json(); } catch {}
  return { res, data };
}

(function setupAccount() {
  $("#account-corner")?.addEventListener("click", openAccountModal);
  $("#footer-account-btn")?.addEventListener("click", openAccountModal);
  $("#account-modal-close")?.addEventListener("click", () => { closeAccountModal(); if (afterLogin) { afterLogin(false); afterLogin = null; } });
  $("#account-backdrop")?.addEventListener("click", (e) => { if (e.target.id === "account-backdrop") { closeAccountModal(); if (afterLogin) { afterLogin(false); afterLogin = null; } } });
  $("#account-tab-login")?.addEventListener("click", () => switchAccountTab("login"));
  $("#account-tab-register")?.addEventListener("click", () => switchAccountTab("register"));

  $("#account-login-form")?.addEventListener("submit", async (e) => {
    e.preventDefault();
    const { res, data } = await postForm("/api/login", new FormData(e.target));
    const err = $("#account-login-error");
    if (!res.ok) { err.textContent = data.detail || "Sign in failed"; return; }
    err.textContent = "";
    await refreshAccountState();
    closeAccountModal();
    if (afterLogin) { afterLogin(true); afterLogin = null; }
  });

  $("#account-register-form")?.addEventListener("submit", async (e) => {
    e.preventDefault();
    const form = new FormData(e.target);
    const { res, data } = await postForm("/api/register", form);
    const err = $("#account-register-error");
    if (!res.ok) { err.textContent = data.detail || "Couldn't create that account"; return; }
    // account exists -> sign them straight in
    const login = new FormData(); login.append("email", form.get("email")); login.append("password", form.get("password"));
    await postForm("/api/login", login);
    err.textContent = "";
    await refreshAccountState();
    closeAccountModal();
    toast("Welcome to Loomwell");
    if (afterLogin) { afterLogin(true); afterLogin = null; }
  });

  $("#account-sign-out")?.addEventListener("click", async () => {
    await fetch("/api/logout", { method: "POST" });
    await refreshAccountState();
    closeAccountModal();
    if (window.onSignedOut) window.onSignedOut();
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") { closeAccountModal(); closeAssistant(); }
  });
  refreshAccountState().then(() => { if (window.onAccountReady) window.onAccountReady(currentUser); });
})();

// ---------- cookie banner ----------
(function () {
  const banner = $("#cookie-banner");
  if (!banner) return;
  let choice = null;
  try { choice = localStorage.getItem("loomwell_cookie_consent"); } catch {}
  if (!choice) banner.hidden = false;
  const set = (v) => { try { localStorage.setItem("loomwell_cookie_consent", v); } catch {} banner.hidden = true; };
  $("#cookie-accept").addEventListener("click", () => set("accepted"));
  $("#cookie-decline").addEventListener("click", () => set("declined"));
})();

// ---------- shop assistant ----------
const assistantEl = $("#assistant");
let assistantGreeted = false;
let assistantFile = null;

function openAssistant(prompt) {
  if (!assistantEl) return;
  assistantEl.hidden = false;
  $("#assistant-fab").classList.add("hidden");
  if (!assistantGreeted) {
    assistantGreeted = true;
    addBubble("bot", "Hi, I'm the Loomwell assistant. Ask me about a product, check stock, delivery or returns — or attach a photo and I'll find similar pieces. For anything else, I'll open a support ticket.");
  }
  if (prompt) sendAssistant(prompt);
  else $("#assistant-input").focus();
}
function closeAssistant() {
  if (!assistantEl) return;
  assistantEl.hidden = true;
  $("#assistant-fab")?.classList.remove("hidden");
}

function addBubble(who, html, isHtml = false) {
  const log = $("#assistant-log");
  const div = document.createElement("div");
  div.className = `bubble bubble-${who}`;
  if (isHtml) div.innerHTML = html; else div.textContent = html;
  log.appendChild(div);
  log.scrollTop = log.scrollHeight;
  return div;
}

function assistantProducts(products) {
  if (!products || !products.length) return "";
  return `<div class="mini-cards">${products.map((p) => `
    <a class="mini-card" href="/shop/design/${p.id}">
      <img src="${p.mockups.front}" alt="" loading="lazy" />
      <span class="mini-title">${escapeHtml(p.title)}</span>
      <span class="mini-price">${inr(p.price_inr)}${typeof p.similarity === "number" ? ` · ${p.similarity}% match` : ""}</span>
      <span class="mini-stock mini-${p.stock.state}">${escapeHtml(p.stock.label)}</span>
    </a>`).join("")}</div>`;
}

async function sendAssistant(text) {
  text = (text || "").trim();
  if (!text && !assistantFile) return;
  const file = assistantFile;
  const userBubble = addBubble("user", file ? `📷 ${file.name}${text ? " — " + text : ""}` : text);
  $("#assistant-input").value = "";
  clearAssistantFile();
  const typing = addBubble("bot", "…");
  typing.classList.add("typing");
  const form = new FormData();
  form.append("message", text);
  if (file) form.append("file", file);
  try {
    const res = await fetch("/api/public/assistant/chat", { method: "POST", body: form });
    const data = await res.json();
    typing.classList.remove("typing");
    typing.innerHTML = `<p>${escapeHtml(data.reply || "Sorry, something went wrong.")}</p>${assistantProducts(data.products)}`;
    if (data.needs_login) { openAccountModal(); }
  } catch {
    typing.classList.remove("typing");
    typing.textContent = "I couldn't reach the shop just now — please try again.";
  }
  $("#assistant-log").scrollTop = $("#assistant-log").scrollHeight;
}

function clearAssistantFile() {
  assistantFile = null;
  const f = $("#assistant-file"); if (f) f.value = "";
  $("#assistant-attached")?.classList.add("hidden");
}

(function setupAssistant() {
  if (!assistantEl) return;
  $("#assistant-fab").addEventListener("click", () => openAssistant());
  $("#open-assistant")?.addEventListener("click", () => openAssistant());
  $("#assistant-close").addEventListener("click", closeAssistant);
  $$("[data-open-assistant]").forEach((b) => b.addEventListener("click", () => openAssistant(b.dataset.prompt)));
  $$("#assistant-chips button").forEach((b) => b.addEventListener("click", () => sendAssistant(b.dataset.prompt)));
  $("#assistant-form").addEventListener("submit", (e) => { e.preventDefault(); sendAssistant($("#assistant-input").value); });
  $("#assistant-file").addEventListener("change", (e) => {
    const f = e.target.files[0];
    if (!f) return;
    assistantFile = f;
    const tag = $("#assistant-attached");
    tag.innerHTML = `Attached: ${escapeHtml(f.name)} <button type="button" class="link-btn" id="assistant-detach">remove</button>`;
    tag.classList.remove("hidden");
    $("#assistant-detach").addEventListener("click", clearAssistantFile);
    $("#assistant-input").focus();
  });
})();
